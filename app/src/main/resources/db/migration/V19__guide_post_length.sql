-- 사용 방법 "글 쓰기" 안내의 본문 글자 수를 새 최대 글자 수(공백 포함 3,000자)로 고친다 (D-121).
-- 관리자가 고친 안내라면 이 문장이 없으니 건드리지 않는다.
UPDATE notices
SET content_md = REPLACE(content_md, '- 제목은 30자, 본문은 1000자까지예요. 사진은 글자 수에 넣지 않아요.',
                         '- 제목은 30자, 본문은 공백 포함 3,000자까지예요. 사진은 글자 수에 넣지 않아요.')
WHERE status = 'NORMAL' AND content_md LIKE '%본문은 1000자까지예요.%';
